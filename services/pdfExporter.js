// services/pdfExporter.js
const PDFDocument = require('pdfkit');

function exportToPdf(choiceListData, res) {
  const doc = new PDFDocument({ margin: 36, size: 'A4' });

  // Stream directly to response
  doc.pipe(res);

  const { inputs, summary, choices } = choiceListData;

  // Header Banner
  doc.rect(36, 36, 523, 56).fill('#1e293b');
  
  doc.fillColor('#ffffff').fontSize(16).font('Helvetica-Bold')
     .text('JoSAA 2024-25 Choice Filling Order Sequence', 50, 48);

  doc.fontSize(9).font('Helvetica')
     .fillColor('#cbd5e1')
     .text(`Generated by JoSAAPrep • Official Data Year: ${summary.dataYear || 2024} • Total Choices: ${choices.length}`, 50, 70);

  // Student Profile Summary Box
  doc.rect(36, 102, 523, 54).strokeColor('#e2e8f0').fillAndStroke('#f8fafc', '#e2e8f0');

  doc.fillColor('#0f172a').fontSize(9).font('Helvetica-Bold');
  doc.text('STUDENT PROFILE & RANK DETAILS', 48, 110);

  doc.font('Helvetica').fontSize(8.5).fillColor('#334155');
  const advText = inputs.jeeAdvRank ? ` | JEE Advanced Rank: ${inputs.jeeAdvRank}` : '';
  doc.text(`JEE Main Rank: ${inputs.jeeMainRank}${advText} | Category: ${inputs.category} | Gender: ${inputs.genderPool}`, 48, 124);
  doc.text(`Home State: ${inputs.homeState || 'All India'} | Priority: ${inputs.priorityOrder.join(' > ')} | Safe: ${summary.safeCount} | Moderate: ${summary.moderateCount} | Ambitious: ${summary.ambitiousCount}`, 48, 138);

  // Table Header
  let y = 170;
  const colX = {
    num: 36,
    inst: 64,
    branch: 215,
    quota: 345,
    cutoff: 380,
    chance: 430,
    nirf: 485,
    lpa: 520
  };

  function drawTableHeader() {
    doc.rect(36, y, 523, 20).fill('#0284c7');
    doc.fillColor('#ffffff').fontSize(7.5).font('Helvetica-Bold');
    doc.text('#', colX.num + 4, y + 6);
    doc.text('Institute Name', colX.inst, y + 6);
    doc.text('Academic Program / Branch', colX.branch, y + 6);
    doc.text('Quota', colX.quota, y + 6);
    doc.text('Cutoff', colX.cutoff, y + 6);
    doc.text('Chance', colX.chance, y + 6);
    doc.text('NIRF', colX.nirf, y + 6);
    doc.text('Avg LPA', colX.lpa, y + 6);
    y += 20;
  }

  drawTableHeader();

  // Table Rows
  doc.font('Helvetica').fontSize(7.5);

  choices.forEach((choice, index) => {
    // Check page break
    if (y > 770) {
      doc.addPage();
      y = 40;
      drawTableHeader();
    }

    const rowBg = index % 2 === 0 ? '#ffffff' : '#f8fafc';
    doc.rect(36, y, 523, 18).fill(rowBg);

    doc.fillColor('#0f172a').font('Helvetica');
    doc.text(String(choice.choice_number), colX.num + 4, y + 5);

    // Institute Name
    const instShort = choice.institute_name.replace('Indian Institute of Technology', 'IIT').replace('National Institute of Technology', 'NIT');
    doc.text(instShort.substring(0, 32), colX.inst, y + 5);

    // Branch Name
    doc.text(choice.branch_name.substring(0, 28), colX.branch, y + 5);

    // Quota
    doc.text(choice.quota || 'AI', colX.quota, y + 5);

    // Cutoff
    doc.text(String(choice.closing_rank), colX.cutoff, y + 5);

    // Chance Label with distinct color
    if (choice.chance === 'Safe') {
      doc.fillColor('#15803d').font('Helvetica-Bold');
    } else if (choice.chance === 'Moderate') {
      doc.fillColor('#b45309').font('Helvetica-Bold');
    } else {
      doc.fillColor('#b91c1c').font('Helvetica-Bold');
    }
    doc.text(choice.chance, colX.chance, y + 5);

    // Reset font
    doc.fillColor('#475569').font('Helvetica');
    doc.text(choice.nirf_rank ? `#${choice.nirf_rank}` : '-', colX.nirf, y + 5);
    doc.text(choice.avg_placement_lpa ? `₹${choice.avg_placement_lpa}L` : '-', colX.lpa, y + 5);

    // Row bottom border
    doc.strokeColor('#f1f5f9').lineWidth(0.5).moveTo(36, y + 18).lineTo(559, y + 18).stroke();

    y += 18;
  });

  // Footer / Disclaimer
  if (y > 750) {
    doc.addPage();
    y = 40;
  }
  y += 15;
  doc.rect(36, y, 523, 36).strokeColor('#cbd5e1').fillAndStroke('#f8fafc', '#cbd5e1');
  doc.fillColor('#64748b').fontSize(7).font('Helvetica')
     .text('DISCLAIMER: This choice filling sequence is algorithmic guidance based on official JoSAA previous year closing cutoffs and NIRF data. Actual seat allotment depends on current year candidate preferences and official JoSAA counselling rules.', 46, y + 8, { width: 500, align: 'left' });

  doc.end();
}

module.exports = { exportToPdf };
