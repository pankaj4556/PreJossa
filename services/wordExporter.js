// services/wordExporter.js
const { Document, Packer, Paragraph, TextRun, Table, TableRow, TableCell, WidthType, AlignmentType, BorderStyle, HeadingLevel } = require('docx');

async function exportToWord(choiceListData, res) {
  const { inputs, summary, choices } = choiceListData;

  const tableHeaderRow = new TableRow({
    tableHeader: true,
    children: [
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: '#', bold: true, color: 'FFFFFF' })], alignment: AlignmentType.CENTER })], shading: { fill: '0284C7' }, width: { size: 6, type: WidthType.PERCENTAGE } }),
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Institute Name', bold: true, color: 'FFFFFF' })] })], shading: { fill: '0284C7' }, width: { size: 34, type: WidthType.PERCENTAGE } }),
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Branch / Program', bold: true, color: 'FFFFFF' })] })], shading: { fill: '0284C7' }, width: { size: 30, type: WidthType.PERCENTAGE } }),
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Quota', bold: true, color: 'FFFFFF' })], alignment: AlignmentType.CENTER })], shading: { fill: '0284C7' }, width: { size: 8, type: WidthType.PERCENTAGE } }),
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Cutoff', bold: true, color: 'FFFFFF' })], alignment: AlignmentType.CENTER })], shading: { fill: '0284C7' }, width: { size: 10, type: WidthType.PERCENTAGE } }),
      new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Chance', bold: true, color: 'FFFFFF' })], alignment: AlignmentType.CENTER })], shading: { fill: '0284C7' }, width: { size: 12, type: WidthType.PERCENTAGE } })
    ]
  });

  const tableRows = choices.map((c, index) => {
    const isEven = index % 2 === 0;
    const bg = isEven ? 'FFFFFF' : 'F8FAFC';
    
    let chanceColor = '15803D';
    if (c.chance === 'Moderate') chanceColor = 'B45309';
    if (c.chance === 'Ambitious') chanceColor = 'B91C1C';

    return new TableRow({
      children: [
        new TableCell({ children: [new Paragraph({ text: String(c.choice_number), alignment: AlignmentType.CENTER })], shading: { fill: bg } }),
        new TableCell({ children: [new Paragraph({ text: c.institute_name })], shading: { fill: bg } }),
        new TableCell({ children: [new Paragraph({ text: c.branch_name })], shading: { fill: bg } }),
        new TableCell({ children: [new Paragraph({ text: c.quota || 'AI', alignment: AlignmentType.CENTER })], shading: { fill: bg } }),
        new TableCell({ children: [new Paragraph({ text: String(c.closing_rank), alignment: AlignmentType.CENTER })], shading: { fill: bg } }),
        new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: c.chance, bold: true, color: chanceColor })], alignment: AlignmentType.CENTER })], shading: { fill: bg } })
      ]
    });
  });

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            text: 'JoSAA 2024-25 Choice Filling Sequence',
            heading: HeadingLevel.HEADING_1,
            alignment: AlignmentType.CENTER
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `JEE Main Rank: ${inputs.jeeMainRank} | Category: ${inputs.category} | Gender: ${inputs.genderPool} | Home State: ${inputs.homeState || 'All India'}`,
                italics: true
              })
            ],
            alignment: AlignmentType.CENTER
          }),
          new Paragraph({ text: '' }), // Spacing
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: [tableHeaderRow, ...tableRows]
          }),
          new Paragraph({ text: '' }),
          new Paragraph({
            children: [
              new TextRun({
                text: 'Disclaimer: Generated by JoSAAPrep. Based on official JoSAA closing ranks and NIRF rankings. Please review before official portal submission.',
                size: 16,
                color: '64748B'
              })
            ]
          })
        ]
      }
    ]
  });

  const buffer = await Packer.toBuffer(doc);
  res.send(buffer);
}

module.exports = { exportToWord };
